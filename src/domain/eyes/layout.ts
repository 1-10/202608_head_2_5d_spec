// GNM の眼球 UV レイアウトと、解剖学的な左右の語。
//
// GNM の眼球メッシュの UV は **UV(0.5, 0.5) を中心とする同心円**（実測）。中心からの半径で
// 3 つの帯に分かれる:
//
//     pupils   半径 [0.0000, 0.0499]
//     irises   半径 [0.0000, 0.1849]
//     scleras  半径 [0.1912, 0.4608]
//
// `irises` の外径 0.1849 と `scleras` の内径 0.1912 の間に 0.0063 の**未割当帯**がある。
// **ここに細工は要らない。** 写真を焼くときの半径の写像は連続なので、帯もその両側と同じ
// 規則でそのまま焼ける。
//
// テクスチャは左右で別に焼く
// --------------------------
// **1 枚を両目で共用しない。** 共用していたのは、描くものを「中心について回転対称な同心円」
// に限っていたから成り立っていた制約で、写真を焼く以上その制約は満たせない（キャッチライトは
// 1 点しかなく、片目だけの傷や充血は非対称）。
//
// 角度の対応は `geometry` が**メッシュから測る**
// ----------------------------------------------
// 「UV の角度が頭部のどの向きに対応するか」をこのモジュールは持たない。写しを置かないのは、
// GNM のアセットが変わったときに黙って嘘になるのを避けるため。
//
// 一辺はここで決めない
// --------------------
// 入口が選ぶ（`application/settings.ExportSettings.eyeTextureSize`）。テクセルと写真画素が
// 1:1 になる一辺は `虹彩半径px / IRIS_OUTER_RADIUS_UV`（実写で 116 前後）で、既定値を選ぶ
// ときの目安として生きている。
//
// テクセルと UV の対応
// --------------------
// `domain/contract` のアトラスと同じ規約: テクセル `(row, col)` の中心が UV
// `((col + 0.5) / W, 1 - (row + 0.5) / H)`。**写真を焼く以上、v の向きは結果を変える**。

/** 同心円の中心（u も v も同じ）。 */
export const EYE_UV_CENTER = 0.5;

/**
 * 瞳孔の外径（UV 単位）。実測 `pupils` の半径 [0.0000, 0.0499]。
 *
 * **この値は焼き込みの写像には使わない**（写真上の瞳孔の大きさは `geometry` の半径 profile
 * が決める）。持っているのは、焼いた絵のどこが瞳孔の帯なのかを検査から指せるようにするため。
 */
export const PUPIL_RADIUS_UV = 0.0499;

/**
 * 虹彩の外径（limbus、UV 単位）。実測 `irises` の半径 [0.0000, 0.1849]。
 *
 * **焼き込みの写像はこの半径を経由する**が、写真の虹彩をここへ合わせることはしない。合わせ
 * ると虹彩の大きさが誰でも公式のサイズになり、その人の虹彩の大きさが失われる。
 */
export const IRIS_OUTER_RADIUS_UV = 0.1849;

/** 強膜の内径（UV 単位）。実測 `scleras` の半径下限。 */
export const SCLERA_INNER_RADIUS_UV = 0.1912;

/**
 * 強膜の外径（UV 単位）。実測 `scleras` の半径上限。
 *
 * これより外は眼球メッシュが使わない領域。**そこも最外周と同色で塗る** — mipmap を降りた
 * ときに未使用領域の色が強膜の縁へ染み出すのを防ぐため。
 *
 * 眼球コンポーネントの頂点のうち**眼球そのもの（眼球内殻）の UV 半径の上限がこの値**でも
 * ある。`geometry` が内殻を選び出したことをこの値で照合する。
 */
export const SCLERA_OUTER_RADIUS_UV = 0.4608;

export const EYE_SIDE_LEFT = 'left';
export const EYE_SIDE_RIGHT = 'right';

/**
 * 眼球テクスチャの側。**解剖学的な左右**（GNM 空間の X の正が解剖学的左）。
 *
 * 写真の見た目の左右ではない。写真が鏡像かどうかで見た目の左右は入れ替わるが、解剖学的な
 * 側は入れ替わらない。どちらの写真の目がどちらの側かは `geometry.assignEyeSides` が相似
 * 変換とメッシュから決める。
 */
export const EYE_SIDES: readonly ['left', 'right'] = [EYE_SIDE_LEFT, EYE_SIDE_RIGHT] as const;

export type EyeSide = (typeof EYE_SIDES)[number];

/**
 * 側 → GNM メッシュの `componentNames` の名前。
 *
 * GNM 側の名前も解剖学的な左右で付いている（実測: `left_eye` の重心が X > 0 = 解剖学的左）。
 * この写しがズレたら `geometry.eyeUvGeometry` が重心の符号で落とす。
 */
export const EYE_COMPONENT_NAMES: Readonly<Record<EyeSide, string>> = {
  left: 'left_eye',
  right: 'right_eye',
};
